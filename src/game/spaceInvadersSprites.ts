/**
 * Creates a standard authentic 22x16 Bunker grid
 * (Rounded top corners, open central archway)
 */
export function createBunkerGrid(): boolean[][] {
  const width = 22;
  const height = 16;
  const grid: boolean[][] = [];

  for (let r = 0; r < height; r++) {
    const row: boolean[] = [];
    for (let c = 0; c < width; c++) {
      let solid = true;

      // Cut off top left and right diagonal corners (smooth dome)
      if (r === 0 && (c < 4 || c >= width - 4)) solid = false;
      if (r === 1 && (c < 3 || c >= width - 3)) solid = false;
      if (r === 2 && (c < 2 || c >= width - 2)) solid = false;
      if (r === 3 && (c < 1 || c >= width - 1)) solid = false;

      // Cut out the central archway at bottom
      if (r >= 10 && c >= 6 && c <= 15) {
        solid = false;
      }
      if (r === 9 && c >= 7 && c <= 14) {
        solid = false;
      }
      if (r === 8 && c >= 8 && c <= 13) {
        solid = false;
      }

      row.push(solid);
    }
    grid.push(row);
  }

  return grid;
}
