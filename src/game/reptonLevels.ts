export function getLevelByPassword(password: string): ReptonLevel | undefined {
  const normalized = password.trim().toUpperCase();
  return REPTON_LEVELS.find(
    l => l.password.toUpperCase() === normalized || l.letter.toUpperCase() === normalized
  );
}
